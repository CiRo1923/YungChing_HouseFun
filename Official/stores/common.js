export const useCommonStore = defineStore('common', () => {
  /* 一開始就是載入中。

    從 false 起頭的話,第一批資料還沒回來的那一段時間畫面是空的 ——
    使用者看到的是「這一頁沒有東西」,然後內容才突然出現。
    從 true 起頭則是先看到載入中,資料到了才換成內容。

    **開與關都走 onIsLoading,接在換頁的那兩個生命週期事件上**:

      page:start   onIsLoading(true)  **打開** —— 新的一頁要重新載入
      page:finish  onIsLoading(false) **關掉** —— 那一頁的資料到齊了

    兩行寫在專案自己的外掛裡(client 端那一支),**不是寫在這裡**:
    有的站還要等圖、等第三方的腳本,那是各站自己的事。

    這個框架的換頁有事件可接,所以兩邊都是事件 —— 不另外包一支
    「回到初始狀態」的別名,那只會多一個名字講同一件事。
    (沒有這組事件的那一份就不一樣:開的那一下沒有地方可掛,
    那邊留了 onReset 給路由的前置守衛用。)

    「等首屏那幾支請求」不在這一組裡 —— 那是 awaitAllPromise 的事,
    而頁面規範本來就要求用它(存檔時會自動包起來)。

    兩邊都沒接的話,畫面會一直停在載入中 —— 那是這個預設值唯一的代價,
    而它看得出來,不像空白畫面那樣會被當成「本來就長這樣」。 */
  const isLoading = ref(true)

  /* 目前的斷點:'p' 桌機 / 't' 平板 / 'm' 手機。

    這裡填的只是「還沒量之前」的暫時值,**不是預設值** ——
    真正的值要在首次繪製之前就寫進來(進入點的 onResize,
    伺服器那一側用 user-agent 猜、瀏覽器這一側量視窗)。

    讀它的不只版面:日期選擇器的浮層要不要改成全螢幕、彈窗依斷點挑的版面,
    都吃這個值。量得太晚的話手機會先照桌機畫一次再跳掉,而那一下不報錯。 */
  const device = ref('p')

  return {
    isLoading,
    device,
  }
})
