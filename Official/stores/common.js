export const useCommonStore = defineStore('common', () => {
  /* 一開始就是載入中。

    從 false 起頭的話,第一批資料還沒回來的那一段時間畫面是空的 ——
    使用者看到的是「這一頁沒有東西」,然後內容才突然出現。
    從 true 起頭則是先看到載入中,資料到了才換成內容。

    **關掉它是使用端的事,而且整個專案只挑一種做法**:

      換頁的生命週期裡統一關    每一頁進來都開、資料回來後由同一個地方關。
                                每一頁都要載入中的專案用這種。
      並行載入的包裝函式        把首屏那幾支包起來,它在最後一定會關
                                (不論成功或失敗)。只有幾頁需要時用這種。
      資料回來之後自己關一次    只有一兩頁需要時用這種。

    **混著用會互相蓋掉。** 統一關的那一層在換頁的當下就關掉,
    而頁面自己那一支晚一步才開 —— 畫面停在載入中,不報錯,
    查起來看不出是兩套做法打架。

    三種都沒做的話,畫面會一直停在載入中 —— 那是這個預設值唯一的代價,
    而它看得出來,不像空白畫面那樣會被當成「本來就長這樣」。

    **本專案用第一種**,開與關都接在 plugins/pageLoading.client.js:
    那支掛在換頁生命週期上,page:start 開、page:finish 在頁面(含 await)
    完成之後關,首次進站的 hydration 也會走到那裡。
    代價是 JS 沒有跑起來的時候遮罩不會消失 —— 伺服器端產出的畫面就帶著它,
    而關閉的那一段在瀏覽器端。這種時候使用者看到的是一直轉,不是空白畫面。 */
  const isLoading = ref(true)

  /* 目前的斷點:'p' 桌機 / 't' 平板 / 'm' 手機。

    這裡填的只是「還沒量之前」的暫時值,**不是預設值** ——
    真正的值要在首次繪製之前就寫進來(進入點的 onResize,
    伺服器那一側用 user-agent 猜、瀏覽器這一側量視窗)。

    讀它的不只版面:日期選擇器的浮層要不要改成全螢幕、彈窗依斷點挑的版面,
    都吃這個值。量得太晚的話手機會先照桌機畫一次再跳掉,而那一下不報錯。 */
  const device = ref('p')

  return {
    isLoading,
    device,
  }
})
