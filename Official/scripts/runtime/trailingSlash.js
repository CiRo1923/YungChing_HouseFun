// 網址結尾一律帶 `/`,這裡是「哪些不補」的唯一一份判準。
//
// 補斜線這件事有三個地方在做,各自負責不同的進站方式:
//   伺服器層  對外部連入、爬蟲、手打網址的原始請求做 301
//   路由表    站內連結的 href 從源頭就帶斜線
//   換頁守衛  前兩者都沒接到的導航(例如程式自己組出來的路徑)
//
// 三處問的是同一個問題:這個路徑該不該補。判準寫成三份的話,
// 改了一處忘了另外兩處不會報錯 —— 只會在某一種進站方式下行為不同,
// 而那種差異要有人剛好從那個入口進來才看得到。
//
// 不補的四種:
//   首頁            它本來就是 `/`
//   已經有斜線      再補就變成兩條
//   帶副檔名        那是檔案不是頁面(圖片、字型、sitemap.xml)
//   底線開頭        框架自己的路徑(建置產物、錯誤頁、圖片處理)
//   api 路徑        給程式讀的端點,補斜線會讓路由對不上
export const isTrailingSlashSkipped = (pathname) =>
  pathname === '/' ||
  pathname.endsWith('/') ||
  pathname.includes('.') ||
  pathname.startsWith('/_') ||
  pathname.startsWith('/api')
